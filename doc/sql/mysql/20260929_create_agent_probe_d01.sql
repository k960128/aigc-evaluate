-- D01：共享探测执行与证据存储。
-- 该脚本只新增动态探测事实，不修改 eval/newpipeline 现有批量评测表。

CREATE TABLE IF NOT EXISTS `agent_probe_execution` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '数据库主键',
    `tenant_id` VARCHAR(64) NOT NULL COMMENT '租户或业务空间标识',
    `actor_id` VARCHAR(64) NOT NULL COMMENT '发起操作者标识',
    `activity_id` VARCHAR(64) NOT NULL COMMENT '评测活动标识',
    `task_id` VARCHAR(64) NOT NULL COMMENT '评测任务标识',
    `run_id` VARCHAR(64) NOT NULL COMMENT '本次运行标识',
    `attempt_id` VARCHAR(64) NOT NULL COMMENT '攻击尝试标识',
    `probe_id` VARCHAR(64) NOT NULL COMMENT '逻辑探测标识',
    `execution_id` VARCHAR(96) COLLATE utf8mb4_bin NOT NULL COMMENT '物理执行唯一标识',
    `trace_id` VARCHAR(64) NOT NULL COMMENT '技术链路追踪标识',
    `authorization_ref` VARCHAR(128) NOT NULL COMMENT '运行授权引用',
    `idempotency_key` VARCHAR(128) COLLATE utf8mb4_bin NOT NULL COMMENT '调用方幂等键，区分大小写',
    `request_fingerprint` CHAR(64) NOT NULL COMMENT '规范化请求SHA-256指纹',
    `target_type` VARCHAR(32) NOT NULL COMMENT '目标类型',
    `target_id` VARCHAR(64) NOT NULL COMMENT '现有目标资源标识',
    `target_snapshot_ref` VARCHAR(160) NOT NULL COMMENT '不可变目标快照引用',
    `target_snapshot_json` LONGTEXT NOT NULL COMMENT '不含凭据的目标快照JSON',
    `risk_id` VARCHAR(128) NOT NULL COMMENT '风险编码',
    `rule_set_version` VARCHAR(128) NOT NULL COMMENT '规则集版本',
    `execution_mode` VARCHAR(40) NOT NULL COMMENT '目标交互模式',
    `required_capabilities` VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '调用方要求的额外目标能力',
    `session_ref` VARCHAR(96) NULL COMMENT '目标会话引用',
    `deadline_at` DATETIME(3) NULL COMMENT '最晚开始目标调用时间',
    `input_evidence_ref` VARCHAR(96) NOT NULL COMMENT '输入证据引用',
    `response_evidence_ref` VARCHAR(96) NULL COMMENT '目标响应证据引用',
    `error_evidence_ref` VARCHAR(96) NULL COMMENT '错误证据引用',
    `status` VARCHAR(32) NOT NULL COMMENT '物理执行状态',
    `error_code` VARCHAR(64) NULL COMMENT '稳定错误编码',
    `error_message` VARCHAR(1000) NULL COMMENT '可安全展示的错误摘要',
    `evidence_completeness` VARCHAR(16) NOT NULL COMMENT '证据完整程度',
    `latency_ms` BIGINT NULL COMMENT '目标调用耗时毫秒',
    `target_calls` BIGINT NOT NULL DEFAULT 0 COMMENT '实际目标调用次数',
    `agent_calls` BIGINT NOT NULL DEFAULT 0 COMMENT '本执行层Agent调用次数',
    `input_tokens` BIGINT NULL COMMENT '输入Token，无法取得时为空',
    `output_tokens` BIGINT NULL COMMENT '输出Token，无法取得时为空',
    `cost` DECIMAL(20, 8) NULL COMMENT '费用，无法取得时为空',
    `currency` VARCHAR(16) NULL COMMENT '费用币种',
    `usage_measurement` VARCHAR(16) NOT NULL COMMENT 'ACTUAL、ESTIMATED或UNAVAILABLE',
    `cancellation_requested` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '是否收到取消意图',
    `cancellation_requested_at` DATETIME(3) NULL COMMENT '首次取消意图时间',
    `accepted_at` DATETIME(3) NOT NULL COMMENT '执行意图受理时间',
    `started_at` DATETIME(3) NULL COMMENT '执行开始时间',
    `finished_at` DATETIME(3) NULL COMMENT '执行结束时间',
    `version` BIGINT NOT NULL DEFAULT 0 COMMENT '状态并发控制版本',
    `create_time` DATETIME(3) NOT NULL COMMENT '创建时间',
    `update_time` DATETIME(3) NOT NULL COMMENT '更新时间',
    `deleted` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '逻辑删除标识',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_agent_probe_tenant_idempotency` (`tenant_id`, `idempotency_key`),
    UNIQUE KEY `uk_agent_probe_execution_id` (`execution_id`),
    KEY `idx_agent_probe_tenant_probe` (`tenant_id`, `probe_id`),
    KEY `idx_agent_probe_run_status` (`tenant_id`, `run_id`, `status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='自动红队动态探测执行事实';

CREATE TABLE IF NOT EXISTS `agent_evidence` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '数据库主键',
    `evidence_ref` VARCHAR(96) COLLATE utf8mb4_bin NOT NULL COMMENT '证据唯一引用',
    `tenant_id` VARCHAR(64) NOT NULL COMMENT '租户或业务空间标识',
    `actor_id` VARCHAR(64) NOT NULL COMMENT '证据创建者标识',
    `owner_type` VARCHAR(64) NOT NULL COMMENT '所属业务对象类型',
    `owner_ref` VARCHAR(96) COLLATE utf8mb4_bin NOT NULL COMMENT '所属物理执行标识',
    `evidence_type` VARCHAR(40) NOT NULL COMMENT '证据类型',
    `media_type` VARCHAR(64) NOT NULL COMMENT '内容媒体类型',
    `content` LONGTEXT NOT NULL COMMENT '原始证据正文，禁止写入普通日志',
    `content_hash` CHAR(64) NOT NULL COMMENT '正文SHA-256摘要',
    `data_class` VARCHAR(24) NOT NULL COMMENT '证据数据分级',
    `create_time` DATETIME(3) NOT NULL COMMENT '创建时间',
    `deleted` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '逻辑删除标识',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_agent_evidence_ref` (`evidence_ref`),
    KEY `idx_agent_evidence_owner` (`tenant_id`, `actor_id`, `owner_ref`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='自动红队受限原始证据';
